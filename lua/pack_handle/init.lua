local function selected_plugin()
	local line = vim.api.nvim_win_get_cursor(state.win)[1]
	return state.plugins[line - 2]
end

function M.delete_selected()
	local plugin = selected_plugin()
	if not plugin then
		notify("Move the cursor to a plugin first", vim.log.levels.WARN)
		return
	end
	local answer = vim.fn.confirm("Delete " .. plugin.spec.name .. "?", "&Delete\n&Cancel", 2)
	if answer ~= 1 then
		return
	end
	local ok, err = pcall(vim.pack.del, { plugin.spec.name }, { force = true })
	if not ok then
		notify("Could not delete " .. plugin.spec.name .. ": " .. err, vim.log.levels.ERROR)
		return
	end
	local config_ok, config_err = remove_from_config(plugin.spec.src)
	if not config_ok then
		notify("Plugin deleted, but config was not updated: " .. config_err, vim.log.levels.WARN)
	else
		notify("Deleted " .. plugin.spec.name)
	end
	M.refresh()
end

function M.add()
	vim.ui.input({ prompt = "Plugin URL: " }, function(url)
		if not url or url == "" then
			return
		end
		url = vim.trim(url)
		if not url:match("^[%w+.-]+://") and not url:match("^[%w_.-]+@[%w_.-]+:") then
			notify("Enter a Git URL (for example https://github.com/owner/repo)", vim.log.levels.WARN)
			return
		end
		local config_ok, config_err = add_to_config(url)
		if not config_ok then
			notify(config_err, vim.log.levels.ERROR)
			return
		end
		local ok, err = pcall(vim.pack.add, { url }, { confirm = false })
		if not ok then
			notify("Saved URL to config, but install failed: " .. err, vim.log.levels.ERROR)
			return
		end
		notify("Added " .. url)
		M.refresh()
	end)
end

function M.open()
	if M.config.config_file == "" then
		notify("You forget to call setup!", vim.log.levels.ERROR)
		return
	end
	if is_valid_window() then
		vim.api.nvim_set_current_win(state.win)
		M.refresh()
		return
	end
	set_highlights()
	state.buf = vim.api.nvim_create_buf(false, true)
	vim.bo[state.buf].bufhidden = "wipe"
	vim.bo[state.buf].buftype = "nofile"
	vim.bo[state.buf].swapfile = false
	vim.bo[state.buf].filetype = "mypack"
	local width, height = floating_dimensions(0.72, 0.62, 60, 10)
	state.win = vim.api.nvim_open_win(state.buf, true, {
		relative = "editor",
		style = "minimal",
		border = "rounded",
		title = " MyPack ",
		title_pos = "center",
		width = width,
		height = height,
		row = math.floor((vim.o.lines - height) / 2),
		col = math.floor((vim.o.columns - width) / 2),
	})
	for key, callback in pairs({
		a = M.add,
		s = M.open_catalog,
		d = M.delete_selected,
		r = M.refresh,
		q = function()
			vim.api.nvim_win_close(state.win, true)
		end,
	}) do
		vim.keymap.set("n", key, callback, { buffer = state.buf, nowait = true, silent = true })
	end
	vim.api.nvim_create_autocmd("BufWipeout", {
		buffer = state.buf,
		once = true,
		callback = function()
			state.buf, state.win = nil, nil
		end,
	})
	M.refresh()
end

function M.setup(opts)
	M.config = vim.tbl_deep_extend("force", M.config, opts or {})
end

return M
